function getProduct(productId: string) {
  const product = products.find((candidate) => candidate.id === productId);

  if (!product) {
    throw new Error(`Unknown mock product: ${productId}`);
  }

  return product;
}

function getBillingAddress(customerId: string) {
  return customers.find((customer) => customer.id === customerId)?.address;
}

function makeInvoiceItem(
  id: string,
  productId: string,
  quantity: number,
): InvoiceItem {
  const product = getProduct(productId);
  const lineTotal = product.sellingPrice * quantity;

  return {
    id,
    productId,
    productName: product.name,
    sku: product.sku,
    quantity,
    unitPrice: product.sellingPrice,
    discount: 0,
    taxRate: 0,
    taxAmount: 0,
    lineTotal,
  };
}

function makeOrderItem(
  id: string,
  productId: string,
  quantity: number,
): OrderItem {
  const product = getProduct(productId);

  return {
    id,
    productId,
    productName: product.name,
    sku: product.sku,
    quantity,
    unitPrice: product.sellingPrice,
    discount: 0,
    lineTotal: product.sellingPrice * quantity,
  };
}

